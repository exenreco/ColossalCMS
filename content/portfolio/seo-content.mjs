export function enrichSeo(entries) {
  for (const e of entries) {
    const [focusKeyword, metaTitle, metaDescription, intro, section] =
      copy[e.slug];
    Object.assign(e, { focusKeyword, metaTitle, metaDescription });
    if (e.slug === "home") e.cmsSlug = "web-developer";
    e.sections.unshift(["Overview", intro]);
    if (section) e.sections.push(section);
  }
  return entries;
}
